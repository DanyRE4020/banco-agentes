\set ON_ERROR_STOP on
CREATE ROLE :"app_user" LOGIN PASSWORD :'app_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
REVOKE CONNECT, TEMPORARY ON DATABASE :"db" FROM PUBLIC;
REVOKE ALL ON SCHEMA public, dim, cfg FROM PUBLIC;
GRANT CONNECT ON DATABASE :"db" TO :"app_user";
GRANT USAGE ON SCHEMA dim, cfg TO :"app_user";
GRANT SELECT ON ALL TABLES IN SCHEMA dim, cfg TO :"app_user";
ALTER DEFAULT PRIVILEGES FOR ROLE :"owner" IN SCHEMA dim, cfg
  GRANT SELECT ON TABLES TO :"app_user";
ALTER ROLE :"app_user" IN DATABASE :"db" SET default_transaction_read_only = on;
